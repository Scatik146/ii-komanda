\ === 0. Трит ===
\ Трит — троичная цифра, как бит, но значений три. Так считала «Сетунь» Брусенцова (1958, серийно с 1959).
1  CONSTANT ДА
0  CONSTANT НЕЗНАЮ
-1 CONSTANT НЕТ
2  CONSTANT ОТСУТСТВУЕТ                  \ атома нет вовсе — не трит и не «нет» (ОЧ-13)

\ === 1. Кирпичи: таблицы ===
: не         ( x -- x )      NEGATE ;                           \ Ф0: да ↔ нет, не знаю остаётся
: и          ( x y -- x )    MIN ;                              \ Ф1: один ноль держит, одна ложь рвёт
: или        ( x y -- x )    MAX ;                              \ Ф1а
: согласие   ( x y -- x )    2DUP = IF DROP ELSE 2DROP 0 THEN ; \ Ф3: одинаково — это, разное — 0
: основание  ( x b -- x )    1 = IF ELSE DROP 0 THEN ;          \ Ф2: есть основание — x, нет — 0
: ворота     ( x -- t )      1 = IF 1 ELSE -1 THEN ;            \ Ф4: только «да» — делать
: возможно   ( x -- t )      -1 = IF -1 ELSE 1 THEN ;           \ Ф5: не «нет» — можно
: не-знаю?   ( x -- t )      0= IF 1 ELSE -1 THEN ;             \ Ф11: не знаю — искать

\ === 2. Значения: правда ли и проверено ли ===
