% Проверка: node proverka-prolog.cjs <путь к drakon-graf/site/experiments/prolog/lib>
% Те же слова и тот же порядок, что в och-slova.fs. У каждого отношения — пример и контрпример.

% === 0. Трит ===
% Трит — троичная цифра, как бит, но значений три. Так считала «Сетунь» Брусенцова (1958, серийно с 1959).
% трит(X, Имя): X — трит с этим именем
% пример: трит(0, не_знаю).  контрпример: трит(2, _).
трит(1, да).
трит(0, не_знаю).
трит(-1, нет).
% атом может отсутствовать вовсе — это не трит и не «нет» (ОЧ-13): значение отсутствует

% === 1. Кирпичи: таблицы ===

% не(X, Y): да ↔ нет, не знаю остаётся (Ф0)
% пример: не(1, -1).  контрпример: не(0, 1).
не(X, Y) :- Y is -X.

% и(X, Y, Z): один ноль держит, одна ложь рвёт (Ф1)
% пример: и(1, 0, 0).  контрпример: и(1, -1, 0).
и(X, Y, Z) :- Z is min(X, Y).

% или(X, Y, Z): Ф1а
% пример: или(-1, 1, 1).  контрпример: или(-1, 0, -1).
или(X, Y, Z) :- Z is max(X, Y).

% согласие(X, Y, Z): одинаково — это значение, разное — 0 (Ф3)
% пример: согласие(1, 1, 1).  контрпример: согласие(1, -1, 1).
согласие(X, X, X).
согласие(X, Y, 0) :- X =\= Y.

% основание(X, Б, Z): есть основание — X, нет — 0 (Ф2)
% пример: основание(-1, 1, -1).  контрпример: основание(1, 0, 1).
основание(X, 1, X).
основание(_, Б, 0) :- Б =\= 1.

% ворота(X, Т): только «да» — делать (Ф4)
% пример: ворота(1, 1).  контрпример: ворота(0, 1).
ворота(1, 1).
ворота(X, -1) :- X =\= 1.

% возможно(X, Т): не «нет» — можно (Ф5)
% пример: возможно(0, 1).  контрпример: возможно(-1, 1).
возможно(-1, -1).
возможно(X, 1) :- X =\= -1.

% не_знаю(X, Т): не знаю — искать (Ф11)
% пример: не_знаю(0, 1).  контрпример: не_знаю(1, 1).
не_знаю(0, 1).
не_знаю(X, -1) :- X =\= 0.

% === 2. Значения: правда ли и проверено ли ===

% запрет(Р, О, Т): «если Р, нужна О»; 1 — нарушено (Ф6)
% пример: запрет(1, -1, 1).  контрпример: запрет(1, 1, 1).
запрет(Р, О, Т) :- не(О, НеО), и(Р, НеО, Т).

% проверено(Стат, Эксп, П): по статусу и экспертизе (Ф7)
% пример: проверено(-1, 1, -1) — черновик.  контрпример: проверено(-1, -1, 1).
проверено(-1, _, -1).
проверено(Стат, 0, 0) :- Стат =\= -1.
проверено(Стат, Эксп, П) :- Стат =\= -1, Эксп =\= 0, по_экспертизе(Стат, Эксп, П).

% по_экспертизе(Стат, Эксп, П): пройдено не меньше нужного — 1, иначе −1
% пример: по_экспертизе(1, 1, 1).  контрпример: по_экспертизе(0, 1, 1).
по_экспертизе(Стат, Эксп, 1) :- Стат >= Эксп.
по_экспертизе(Стат, Эксп, -1) :- Стат < Эксп.

% пров_к_сроку(Пров, Срок, П): часы на замке — до срока 0 (ОЧ-03)
% пример: пров_к_сроку(1, -1, 0).  контрпример: пров_к_сроку(1, -1, 1).
пров_к_сроку(Пров, Срок, П) :- основание(Пров, Срок, П).

% срабатывает(Посылка, Т): посылка «отсутствует» правило не запускает (Ф9, ОЧ-13)
% пример: срабатывает(0, 1).  контрпример: срабатывает(отсутствует, 1).
срабатывает(отсутствует, -1).
срабатывает(П, Т) :- трит(П, _), возможно(П, Т).

% экспертиза(X, Вердикт, Незав, Новое): «не знаю» снимает только независимый (ОЧ-19)
% пример: экспертиза(0, -1, 1, -1).  контрпример: экспертиза(0, 1, 0, 1).
экспертиза(X, _, _, X) :- X =\= 0.
экспертиза(0, Вердикт, Незав, Новое) :- основание(Вердикт, Незав, Новое).

% ошибка_сказки(Расходится, Оговорка, Т): условность без оговорки (ОЧ-14)
% пример: ошибка_сказки(1, -1, 1).  контрпример: ошибка_сказки(1, 1, 1).
ошибка_сказки(Р, О, Т) :- запрет(Р, О, Т).

% спор(X, Y, Z): двое спорят — не знаю (ОЧ-15, Б6)
% пример: спор(1, -1, 0).  контрпример: спор(1, -1, 1).
спор(X, Y, Z) :- согласие(X, Y, Z).

% === 3. Вывод: следует ли, для всех ли, есть ли ===

% по_списку(Есть, Полный, Т) = есть ∨ (¬полный ∧ 0): нашли — 1; точно не нашли по полному списку — −1; иначе 0 (неясная находка — 0, книга Е.6)
% пример: по_списку(-1, -1, 0).  контрпример: по_списку(-1, -1, -1).
по_списку(Есть, Полный, Т) :- не(Полный, НП), и(НП, 0, A), или(Есть, A, Т).

% следует(Vx, Контр, Vy, Т): пример есть, контрпримера нет (Ф12, ОЧ-23)
% пример: следует(1, -1, 1, 1).  контрпример: следует(-1, -1, 1, 1) — «из ничего».
следует(Vx, Контр, Vy, Т) :- не(Контр, НеК), и(НеК, Vy, Х), и(Vx, Х, Т).

% для_всех(Контр, Т): ни одного контрпримера (Ф13, ОЧ-24)
% пример: для_всех(-1, 1).  контрпример: для_всех(0, 1).
для_всех(Контр, Т) :- не(Контр, Т).

% не_доказано(П, Т): «не» над выведенным; не определено — 0 (Ф15, ОЧ-25: не нашёл — не знаю; «нет» — по контрпримеру или полному списку)
% пример: не_доказано(0, 0).  контрпример: не_доказано(0, -1).
не_доказано(П, Т) :- не(П, Т).

% равносильно(Xy, Yx, Т): следует в обе стороны (Ф16)
% пример: равносильно(1, 1, 1).  контрпример: равносильно(1, 0, 1).
равносильно(Xy, Yx, Т) :- и(Xy, Yx, Т).

% === 4. Действия: делать ли ===

% восстановимо(Обр, Реш, Т): обратимо или автор решил (Ф8, Б8)
% пример: восстановимо(-1, 1, 1).  контрпример: восстановимо(-1, 0, 1).
восстановимо(Обр, Реш, Т) :- ворота(Реш, Р), или(Обр, Р, Т).

% наружу(Ист, Пров, Т): только «и там, и там 1» (ОЧ-05)
% пример: наружу(1, 1, 1).  контрпример: наружу(1, 0, 1).
наружу(Ист, Пров, Т) :- и(Ист, Пров, Х), ворота(Х, Т).

% на_экспертизу(Эксп, Стат, Т): черновики не носят (ОЧ-06)
% пример: на_экспертизу(1, 0, 1).  контрпример: на_экспертизу(1, -1, 1).
на_экспертизу(Эксп, Стат, Т) :- ворота(Эксп, А), возможно(Стат, Б), и(А, Б, Т).

% включить(Задан, Т): нет числа — нет механизма (ОЧ-12)
% пример: включить(1, 1).  контрпример: включить(0, 1).
включить(Задан, Т) :- ворота(Задан, Т).

% прочерк(Обязательно, Т): прочерк принят, только если точно необязательно (ОЧ-16)
% пример: прочерк(-1, 1).  контрпример: прочерк(0, 1).
прочерк(Обязательно, Т) :- не(Обязательно, Х), ворота(Х, Т).

% собирать(ЕстьЧасти, Т), с_нуля(ЕстьЧасти, Т): сначала из того, что есть (ОЧ-21)
% пример: собирать(1, 1), с_нуля(-1, 1).  контрпример: с_нуля(0, 1).
собирать(Есть, Т) :- ворота(Есть, Т).
с_нуля(Есть, Т) :- не(Есть, Х), ворота(Х, Т).

% придумывать(Есть, Т): только если точно нигде нет (ОЧ-22)
% пример: придумывать(-1, 1).  контрпример: придумывать(0, 1).
придумывать(Есть, Т) :- не(Есть, Х), ворота(Х, Т).

% искать(Есть, Т): не знаю — ищу (ОЧ-21, ОЧ-22, ОЧ-26)
% пример: искать(0, 1).  контрпример: искать(1, 1).
искать(Есть, Т) :- не_знаю(Есть, Т).

% параллельно(Незав, Быстрее, Т): не знаешь, что быстрее, — по очереди (ОЧ-27)
% пример: параллельно(1, 1, 1).  контрпример: параллельно(1, 0, 1).
параллельно(Незав, Быстрее, Т) :- ворота(Незав, А), ворота(Быстрее, Б), и(А, Б, Т).

% заменить(Совпало, Откат, Т): новое делает ровно то же и откат готов (ОЧ-18)
% пример: заменить(1, 1, 1).  контрпример: заменить(1, 0, 1).
заменить(Совпало, Откат, Т) :- и(Совпало, Откат, Х), ворота(Х, Т).

% без_чужих_глаз(Эксп, Чужая, Т): 1 — ошибка: нужна экспертиза, а чужой проверки нет (Б5)
% пример: без_чужих_глаз(1, 0, 1).  контрпример: без_чужих_глаз(1, 1, 1).
без_чужих_глаз(Эксп, Чужая, Т) :- ворота(Эксп, А), ворота(Чужая, Б), запрет(А, Б, Т).

% ответ(X, Что): на всё три ответа (ОЧ-26)
% пример: ответ(0, ищу).  контрпример: ответ(0, делаю).
ответ(X, делаю) :- ворота(X, 1).
ответ(X, ищу) :- не_знаю(X, 1).
ответ(X, не_делаю) :- не(X, Y), ворота(Y, 1).

% === 5. Время ===

% было(Найдено, Полный, Т): Т1;  всегда_было(Нарушение, Полный, Т): Т2
% пример: было(1, -1, 1), всегда_было(-1, 1, 1).  контрпример: всегда_было(-1, -1, 1).
было(Найдено, Полный, Т) :- по_списку(Найдено, Полный, Т).
всегда_было(Нарушение, Полный, Т) :- по_списку(Нарушение, Полный, Х), не(Х, Т).

% к_сроку(Сделано, Срок, Т): до срока 0, после — факт (Т3)
% пример: к_сроку(-1, -1, 0).  контрпример: к_сроку(-1, -1, -1).
к_сроку(Сделано, Срок, Т) :- по_списку(Сделано, Срок, Т).

% пока_цело(Нарушение, Т): «всегда будет» не бывает 1 (Т4)
% пример: пока_цело(-1, 0).  контрпример: пока_цело(-1, 1).
пока_цело(1, -1).
пока_цело(Нарушение, 0) :- Нарушение =\= 1.

% годно(Ист, Годно, Т): устаревшее — 0, не −1 (Т5)
% пример: годно(1, -1, 0).  контрпример: годно(1, -1, -1).
годно(Ист, Годно, Т) :- основание(Ист, Годно, Т).

% после(СделаноА, Т): Б — только после А (Т6)
% пример: после(1, 1).  контрпример: после(0, 1).
после(СделаноА, Т) :- ворота(СделаноА, Т).

% прогноз_сейчас(Прогноз, Т): в Реальности до срока 0 (Т7)
% пример: прогноз_сейчас(1, 0).  контрпример: прогноз_сейчас(1, 1).
прогноз_сейчас(Прогноз, 0) :- трит(Прогноз, _).

% неотвратимо(А, Б, В, Полный, Т): во всех вариантах полного списка (Т8); список не полон — 0
% пример: неотвратимо(1, 1, 1, 1, 1).  контрпример: неотвратимо(1, 1, 1, 0, 1).
неотвратимо(А, Б, В, Полный, Т) :- согласие(А, Б, Х), согласие(Х, В, У), основание(У, Полный, Т).

% может_быть(А, Б, В, Т): хоть в одном варианте; все «не знаю» — 0 (Т9)
% пример: может_быть(-1, 1, -1, 1).  контрпример: может_быть(0, 0, 0, -1).
может_быть(А, Б, В, Т) :- или(А, Б, Х), или(Х, В, Т).

% под_рукой(А, Б, В, Т): держать под рукой — действие от «может быть» (Т9)
% пример: под_рукой(-1, 1, -1, 1).  контрпример: под_рукой(0, 0, 0, 1).
под_рукой(А, Б, В, Т) :- может_быть(А, Б, В, Х), ворота(Х, Т).

% обещать(Неотвр, Решено, Т): неотвратимое или своё решённое (ОЧ-29)
% пример: обещать(0, 1, 1).  контрпример: обещать(0, 0, 1).
обещать(Неотвр, Решено, Т) :- ворота(Неотвр, А), ворота(Решено, Б), или(А, Б, Т).

% хватит(Неотвр, Вальд, Т): итог неотвратим или Вальд сказал «стоп» (ОЧ-20)
% пример: хватит(0, 1, 1).  контрпример: хватит(0, 0, 1).
хватит(Неотвр, Вальд, Т) :- ворота(Неотвр, А), ворота(Вальд, Б), или(А, Б, Т).

% готовиться(Неотвр, Т), ещё_не_поздно(Неотвр, Т): неизбежное — готовиться (ОЧ-30)
% пример: готовиться(1, 1), ещё_не_поздно(0, 1).  контрпример: готовиться(0, 1).
готовиться(Неотвр, Т) :- ворота(Неотвр, Т).
ещё_не_поздно(Неотвр, Т) :- не_знаю(Неотвр, Т).

% === 5а. Сомнение и ответ ученику ===

% усомниться(X, Сомнение, Новое): сомнение возвращает в 0, пока не проверим (ОЧ-31)
% пример: усомниться(1, 1, 0).  контрпример: усомниться(1, 1, 1).
усомниться(X, Сомнение, Новое) :- не(Сомнение, Б), основание(X, Б, Новое).

% ответ_ученику(X, Что): не знаю — так и говорю (ОЧ-32)
% пример: ответ_ученику(0, пока_не_знаю_проверю).  контрпример: ответ_ученику(0, да).
ответ_ученику(X, да) :- ворота(X, 1).
ответ_ученику(X, нет) :- не(X, Y), ворота(Y, 1).
ответ_ученику(X, пока_не_знаю_проверю) :- не_знаю(X, 1).

