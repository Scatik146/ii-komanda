% === 6. Пример вывода: «для всех» по полному списку (ОЧ-24, ОЧ-25) ===

% данные примера: урок 23.11 — список полный; урок 24.11 — ещё пополняется
урок(урок_23).
урок(урок_24).
слово_урока(урок_23, пароль).
слово_урока(урок_23, фишинг).
слово_урока(урок_24, пароль).
проверено_слово(пароль).
проверено_слово(фишинг).
список_полный(урок_23).

% есть_контрпример(Урок): в уроке есть непроверенное слово
% пример: нет у урока 23.  контрпример: есть_контрпример(урок_23).
есть_контрпример(Урок) :- слово_урока(Урок, С), \+ проверено_слово(С).

% все_проверены(Урок, Т): ни одного контрпримера в полном списке; урок(Урок) первым — чтобы \+ получал связанное
% пример: все_проверены(урок_23, 1); все_проверены(урок_24, 0).  контрпример: все_проверены(урок_24, 1).
все_проверены(Урок, 1) :- урок(Урок), список_полный(Урок), \+ есть_контрпример(Урок).
все_проверены(Урок, -1) :- урок(Урок), есть_контрпример(Урок).
все_проверены(Урок, 0) :- урок(Урок), \+ список_полный(Урок), \+ есть_контрпример(Урок).
