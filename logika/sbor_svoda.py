# stroki_atoma: блок ```атом для одного атома
def stroki_atoma(a):
    polya = [("id", f"{a['n']}-{a['imya']}"), ("тип", a["tip"]), ("описание", a["opis"]),
             ("назначение", a["nazn"]), ("истинность", a["ist"]), ("статус", a["status"]),
             ("состав", a["sostav"]), ("источник", a["ist_"]),
             ("пример", a["pr"]), ("контрпример", a["kpr"])]
    blok = ["```атом"] + [f"{k}: {v}" for k, v in polya]
    blok += ["история:", f"- {DATA} | Марьям | {a['hist']}", "```"]
    return blok

# oglavlenie: верхнее слово — слои снизу вверх одной таблицей
