\ === 1. Основной базис: и, не, ворота, 0 ===
: не       ( x -- y )    NEGATE ;                  \ меняет знак
: и        ( x y -- z )  MIN ;                     \ меньшее
: ворота   ( x -- t )    1 = IF 1 ELSE -1 THEN ;   \ только 1
0 CONSTANT НОЛЬ                                    \ «не знаю»

\ === 2. Следующий уровень ===
: не-и      ( x y -- z )  и не ;                   \ ¬(x ∧ y)
: или       ( x y -- z )  не SWAP не не-и ;        \ ¬(¬x ∧ ¬y) - большее
: погасло   ( x -- t )    ворота не ;              \ ¬ворота(x)
: не-знаю?  ( x -- t )    DUP погасло SWAP не погасло и ;   \ только 0
: возможно  ( x -- t )    не погасло ;             \ ¬ворота(¬x) - всё, кроме -1
: с-нулём   ( x -- z )    НОЛЬ и ;                 \ x ∧ 0
: подтвердить ( a y -- z ) с-нулём или ;           \ «нет» в a - только если y = -1

\ === 3. Действия ===
: основание ( x b -- z )  DUP >R и R> не подтвердить ;        \ (x ∧ b) ∨ (¬b ∧ 0)
: согласие  ( x y -- z )  2DUP и ROT ROT или подтвердить ;    \ (x ∧ y) ∨ ((x ∨ y) ∧ 0)
: есть-ли   ( н п -- t )  не подтвердить ;                    \ нашёл ∨ (¬полный ∧ 0)
: срабатывает ( x -- t )  ОТСУТСТВУЕТ = IF -1 ELSE 1 THEN ;

