# prochitat: текст файла
def prochitat(put):
    with open(put, encoding='utf-8') as f:
        tekst = f.read()
    return tekst


# vyvod: что печатает слово программы (перехват stdout)
def vyvod(slovo, *argi):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        slovo(*argi)
    return buf.getvalue()


# svezhij_summatory: вывод summatory.py совпадает с rezultat-summatory.txt
def svezhij_summatory():
    return vyvod(summatory.glavnoe) == prochitat(os.path.join(KALK, 'rezultat-summatory.txt'))


# svezhij_x: блок сумматора в rezultat-x.txt совпадает с новым счётом
def svezhij_x():
    novyj = vyvod(px.pechat_shemy, px.shema_summatora(), 1)
    return prochitat(os.path.join(P4, 'rezultat-x.txt')).startswith(novyj)


# svezhij_pokupatel: первый опыт pokupatel.py (умножитель, без неизвестного, T = 8) совпадает с выводом в файле
def svezhij_pokupatel():
    novyj = vyvod(pk.pechat_opyta, px.shema_umnozhitelya(4), 8, [], 'без неизвестного')
    return novyj in prochitat(os.path.join(P4, 'rezultat-pokupatel.txt'))


# trity: число → цифры −1, 0, 1 от старшей
def trity(n):
    cf = []
    while n != 0:
        c = (n + 1) % 3 - 1
        cf.insert(0, c)
        n = (n - c) // 3
    return cf


# primer_4_4: 4 = ++, 4 + 4 = +0− (= 9 − 1 = 8)
def primer_4_4():
    return trity(4) == [1, 1] and trity(8) == [1, 0, -1]


# primer_kart: 0111 + 0001: «порождаю», «пропускаю», «пропускаю», «гашу» снизу; склейка трёх нижних — «порождаю»
def primer_kart():
    a, b = [1, 1, 1, 0], [1, 0, 0, 0]
    karty = [summatory.karta_razryada(2, x, y) for x, y in zip(a, b)]
    nizhnie = karty[0]
    for k in karty[1:3]:
        nizhnie = tuple(k[c] for c in nizhnie)
    return karty == [(1, 1), (0, 1), (0, 1), (0, 0)] and nizhnie == (1, 1)


# primer_X: полный сумматор, a = X, b = c = 1: перенос точно 1, наша — «не знаю», способ 1: сумма уверенно 0
def primer_X():
    sh = px.shema_summatora()
    s = sh['схема']
    a, b, c = (op[0] for op in sh['входы'])
    zn = {a: np.array([0]), b: np.array([1]), c: np.array([1])}
    tochno = px.tochno(s, zn, sh['выходы'], [[a]])[0]
    nasha = px.nash(s, zn, sh['выходы'], [[a]], 'трит')[0]
    dva = px.dvuznachnyj(s, zn, sh['выходы'], [[a]])[0]
    return int(tochno[1][0]) == 1 and int(nasha[1][0]) == -1 and int(tochno[0][0]) == -1 and int(dva[0][0]) == 0


# karty: у битов 3 карты переноса, у тритов 7, чистого «пропускаю» (−1, 0, 1) у тритов нет
def karty():
    t = summatory.karty_vsego(3)
    return len(summatory.karty_vsego(2)) == 3 and len(t) == 7 and (-1, 0, 1) not in t


# pary: каждая фраза есть в книге и её строка есть в выводе
def pary():
    kniga = prochitat(KNIGA)
    fajly = {'S': prochitat(os.path.join(KALK, 'rezultat-summatory.txt')),
             'X': prochitat(os.path.join(P4, 'rezultat-x.txt')),
             'K': prochitat(os.path.join(P4, 'rezultat-pokupatel.txt'))}
    oshibki = [f for f, v, k in PARY if f not in kniga or v not in fajly[k]]
    for f in oshibki:
        print('  нет пары:', f.replace('\n', ' ')[:90])
    return not oshibki


# glavnoe: все проверки, итог строкой
def glavnoe():
    proverki = [('вывод summatory.py свежий', svezhij_summatory), ('вывод proverka_x.py (сумматор) свежий', svezhij_x),
                ('вывод pokupatel.py (первый опыт) свежий', svezhij_pokupatel),
                ('4 + 4 = +0−', primer_4_4), ('0111 + 0001 картами переноса = 1000', primer_kart),
                ('перенос при a = X, b = c = 1', primer_X), ('карт переноса 3 и 7', karty),
                (f'числа текста — в выводе программ ({len(PARY)} пар)', pary)]
    oshibok = 0
    for imya, f in proverki:
        ok = f()
        oshibok += not ok
        print('да ' if ok else 'НЕТ', imya)
    print(f'П.3 (сумматор) и П.4 части 2: проверок {len(proverki)}, ошибок {oshibok}')
    return oshibok


