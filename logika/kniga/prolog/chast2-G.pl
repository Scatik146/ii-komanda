пример(г4, 'Брусенцов буквально на битах: ложное условие - 0', (findall(Т, (бит2(X), бит2(Y), брусенцов(X, Y, Т)), [0, 0, -1, 1]))).
пример(г4, 'x → x: Клини (1, 0, 1)', вектор1(сам_в_себя, [1, 0, 1])).
пример(г4, 'x → x: Лукасевич (1, 1, 1)', вектор1(сам_в_себя_л, [1, 1, 1])).
пример(г4, 'Клини и Лукасевич расходятся только в (0, 0)', findall(X-Y, (тройка(X), тройка(Y), сл(X, Y, A), лукасевич(X, Y, B), A =\= B), [0-0])).
контрпример(г4, 'Клини: 0 → 0 = 1', сл(0, 0, 1)).
% сам_в_себя(X, Т), сам_в_себя_л(X, Т): x → x по Клини и по Лукасевичу
сам_в_себя(X, Т) :- сл(X, X, Т).
сам_в_себя_л(X, Т) :- лукасевич(X, X, Т).
