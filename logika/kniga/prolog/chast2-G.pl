% лукасевич(X, Y, Т): min(1, 1 - x + y)
лукасевич(X, Y, Т) :- Т is min(1, 1 - X + Y).
% брусенцов(X, Y, Т): буквально xy ∨ σx′, σ = 0 - (x ∧ y) ∨ (¬x ∧ 0)
брусенцов(X, Y, Т) :- и(X, Y, A), не(X, Н), или_ноль(A, Н, Т).

% === Г.1. Стрелка проверяет журнал ===
% день(Н, Дождь, Зонт): неделя «дождь → зонт»
день(1, 1, 1).
день(2, -1, -1).
день(3, -1, 1).
день(4, 1, 1).
день(5, -1, -1).
день(6, 1, -1).
день(7, -1, -1).
пример(г1, 'на битах: три правды, одна ложь', (findall(Т, (бит2(X), бит2(Y), сл(X, Y, Т)), [1, 1, -1, 1]))).
пример(г1, 'нарушение только в субботу', findall(Н, (день(Н, Д, З), сл(Д, З, -1)), [6])).
контрпример(г1, '«нет-нет» - нарушение', сл(-1, -1, -1)).

% === Г.3. «Все» - и никого ===
% ученик(Н, Был, Писал): пустой класс - никто не был, никто не писал
ученик(Н, -1, -1) :- between(1, 25, Н).
% все_по_стрелке(Т): стрелка «был → писал» по всем ученикам - меньшее
все_по_стрелке(Т) :- findall(С, (ученик(_, X, Y), сл(X, Y, С)), Л), min_list(Л, Т).
% все_по_ОЧ23: есть кто был, нет «был, а не писал», есть кто писал
все_по_оч23 :- ученик(_, 1, _), \+ ученик(_, 1, -1), ученик(_, _, 1).
пример(г3, 'пустой класс: стрелка - «да»', все_по_стрелке(1)).
контрпример(г3, 'пустой класс: по ОЧ-23 - «все писали»', все_по_оч23).

