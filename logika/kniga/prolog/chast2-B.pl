% сл(X, Y, Z): x → y = ¬x ∨ y (договор части 1)
сл(X, Y, Z) :- не(X, A), или(A, Y, Z).
% экв(X, Y, Z): x ≡ y = (x → y) ∧ (y → x)
экв(X, Y, Z) :- сл(X, Y, A), сл(Y, X, B), и(A, B, Z).

% знач(Терм, Т): значение терма из чисел и слов не, и, или, сл, экв
знач(Т, Т) :- number(Т).
знач(не(A), Т) :- знач(A, X), не(X, Т).
знач(Терм, Т) :- Терм =.. [Слово, A, B], memberchk(Слово, [и, или, сл, экв]), знач_два(Слово, A, B, Т).
% знач_два(Слово, A, B, Т): действие с двумя буквами над значениями
знач_два(Слово, A, B, Т) :- знач(A, X), знач(B, Y), call(Слово, X, Y, Т).

% закон(Название, Звезда, Буквы, Левая, Правая): буквы - переменные Пролога
