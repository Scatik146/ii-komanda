% поломка(Имя, Значения, Набор): набор из Значений, где части закона не совпали
поломка(Имя, Знач, Буквы) :- закон(Имя, _, Буквы, Л, П), maplist(из(Знач), Буквы), разные(Л, П).
% из(Знач, X): X - одно из значений
из(Знач, X) :- member(X, Знач).
% разные(Л, П): значения частей не совпали
разные(Л, П) :- знач(Л, A), знач(П, B), A =\= B.
% держится(Имя, Знач): поломок нет
держится(Имя, Знач) :- закон(Имя, _, _, _, _), \+ поломка(Имя, Знач, _).
% сколько(Цель, Н): сколько решений
сколько(Шаблон-Цель, Н) :- findall(Шаблон, Цель, Х), length(Х, Н).

