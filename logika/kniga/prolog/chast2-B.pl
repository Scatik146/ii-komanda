% никогда(Имя, Т): левая часть звёздного закона никогда не равна Т (на тритах)
никогда(Имя, Т) :- закон(Имя, да, Б, Л, _), \+ (maplist(из([-1, 0, 1]), Б), знач(Л, Т)).
% держится_если_известна(Имя, N): закон держится, если N-я буква - да или нет
держится_если_известна(Имя, N) :- закон(Имя, да, Б, Л, П), \+ (nth1(N, Б, X), member(X, [-1, 1]), maplist(из([-1, 0, 1]), Б), разные(Л, П)).
