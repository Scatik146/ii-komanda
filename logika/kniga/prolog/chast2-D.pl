% === Д.1. Морское сражение всерьёз ===
% знач_в(Формула, Набор, Т): формула от букв p, k, s, d на наборе Буква-значение
знач_в(Ф, Набор, Т) :- подставить(Ф, Набор, Ч), знач(Ч, Т).
% подставить(Ф, Набор, Ч): буквы - их значения
подставить(Б, Набор, Ч) :- atom(Б), memberchk(Б-Ч, Набор), !.
подставить(Ф, Набор, Ч) :- Ф =.. [С | А], maplist(подставить_в(Набор), А, АЧ), Ч =.. [С | АЧ].
% подставить_в(Набор, Ф, Ч): то же с другим порядком аргументов
подставить_в(Набор, Ф, Ч) :- подставить(Ф, Набор, Ч).
% согласие_всех(Ответы, Т): согласие по всем вариантам - все 1 - 1, все -1 - -1, иначе 0
согласие_всех([X | О], Т) :- foldl(согласие_с, О, X, Т).
% согласие_с(X, A, Т): согласие(A, X) - порядок аргументов для foldl
согласие_с(X, A, Т) :- согласие(A, X, Т).
% или_всех(Ответы, Т): ИЛИ по всем вариантам (пустой список - -1)
или_всех(О, Т) :- foldl(или_с, О, -1, Т).
% или_с(X, A, Т): или(A, X)
или_с(X, A, Т) :- или(A, X, Т).
% свести(Ответы, Т): по вариантам - это согласие всех
свести(О, Т) :- согласие_всех(О, Т).
% по_вариантам(Ф, Варианты, Т): формула целиком в каждом варианте, потом свести
по_вариантам(Ф, В, Т) :- findall(О, (member(Н, В), знач_в(Ф, Н, О)), ОО), свести(ОО, Т).
% варианты
сражение([[p-1], [p-(-1)]]).
урок([[k-1, s-(-1)], [k-(-1), s-1]]).
урок_и_кино([[k-1, s-(-1)], [k-(-1), s-1], [k-(-1), s-(-1)]]).
бой_и_дождь(В) :- findall([p-A, d-B], (бит2(A), бит2(B)), В).
% формулы(Г, Ф): все формулы от p из не, и, или глубины не больше Г
формулы(0, [p]).
формулы(Г, Ф) :- Г > 0, Г1 is Г - 1, формулы(Г1, Ф1), findall(Н, новая(Ф1, Н), НН), append(Ф1, НН, Ф2), list_to_set(Ф2, Ф).
% новая(Ф1, Н): не(f), и(f, g), или(f, g) из списка
новая(Ф1, не(F)) :- member(F, Ф1).
новая(Ф1, Н) :- member(С, [и, или]), member(F, Ф1), member(G, Ф1), Н =.. [С, F, G].
% расходится(Ф, Т, В): таблица при p = 0 и перебор отвечают по-разному
расходится(Ф, Т, В) :- знач_в(Ф, [p-0], Т), сражение(С), по_вариантам(Ф, С, В), Т =\= В.
пример(д1, 'сражение: p ∨ ¬p по вариантам - 1', (сражение(С), по_вариантам(или(p, не(p)), С, 1))).
пример(д1, 'сражение: p ∧ ¬p по вариантам - -1', (сражение(С), по_вариантам(и(p, не(p)), С, -1))).
пример(д1, 'сражение: p и ¬p по отдельности - 0', (сражение(С), по_вариантам(p, С, 0), по_вариантам(не(p), С, 0))).
пример(д1, 'таблица: p ∨ ¬p при p = 0 - 0', знач_в(или(p, не(p)), [p-0], 0)).
пример(д1, 'урок: контрольная или самостоятельная - 1', (урок(У), по_вариантам(или(k, s), У, 1))).
пример(д1, 'забыли «кино» - 0', (урок_и_кино(У), по_вариантам(или(k, s), У, 0))).
пример(д1, 'бой или дождь - согласны: 0', (бой_и_дождь(В), по_вариантам(или(p, d), В, 0), знач_в(или(p, d), [p-0, d-0], 0))).
пример(д1, '10 неизвестных - 1024 варианта', (X is 2 ^ 10, X =:= 1024)).
пример(д1, '37 формул, 12 расхождений', (формулы(2, Ф), length(Ф, 37), findall(F, (member(F, Ф), расходится(F, _, _)), Р), length(Р, 12))).
пример(д1, 'таблица не врёт - недоговаривает: везде 0', (формулы(2, Ф), forall((member(F, Ф), расходится(F, Т, В)), (Т =:= 0, В =\= 0)))).
пример(д1, 'по сути расхождений два: (1, 0, 1) и (-1, 0, -1)', (формулы(2, Ф), findall(Век, (member(F, Ф), расходится(F, _, _), вектор_ф(F, Век)), ВВ), sort(ВВ, [[-1, 0, -1], [1, 0, 1]]))).
контрпример(д1, 'перебор - гадалка: «будет» - 1', (сражение(С), по_вариантам(p, С, 1))).
% вектор_ф(F, В): формула от p при p = -1, 0, 1
вектор_ф(F, В) :- findall(Т, (тройка(X), знач_в(F, [p-X], Т)), В).

% === Д.2. Неотвратимо и может быть ===
% Полный: 1 - список полный, -1 - нет.
% неотвратимо(О, Полный, Т): основание(согласие всех вариантов, полный)
неотвратимо(О, Полный, Т) :- согласие_всех(О, С), основание(С, Полный, Т).
% может_быть(О, Полный, Т): есть ли (нашёл = ИЛИ всех вариантов, полный)
может_быть(О, Полный, Т) :- или_всех(О, Н), есть_ли(Н, Полный, Т).
% расписание: математика во всех, физкультура в одном, химии нет
предмет(математика, [1, 1, 1]).
предмет(физкультура, [-1, 1, -1]).
предмет(химия, [-1, -1, -1]).
пример(д2, 'математика: неотвратимо 1', (предмет(математика, О), неотвратимо(О, 1, 1))).
пример(д2, 'физкультура: неотвратимо 0, может быть 1', (предмет(физкультура, О), неотвратимо(О, 1, 0), может_быть(О, 1, 1))).
пример(д2, 'химия: неотвратимо -1, может быть -1', (предмет(химия, О), неотвратимо(О, 1, -1), может_быть(О, 1, -1))).
пример(д2, 'список неполный: математика - неотвратимо 0', (предмет(математика, О), неотвратимо(О, -1, 0))).
пример(д2, 'список неполный: физкультура - может быть 1', (предмет(физкультура, О), может_быть(О, -1, 1))).
пример(д2, 'список неполный: химия - может быть 0', (предмет(химия, О), может_быть(О, -1, 0))).
пример(д2, '99 да и 1 нет - неотвратимо 0', (findall(1, between(1, 99, _), Л), append(Л, [-1], О), неотвратимо(О, 1, 0))).
пример(д2, 'неотвратимое тем более может быть; на «нет» сходятся', forall(список_до_4(О), слова_честны(О))).
контрпример(д2, 'неполный список, все нет - может быть -1', может_быть([-1, -1, -1], -1, -1)).
% список_до_4(О): все списки из 1 и -1 длиной 1..4
список_до_4(О) :- between(1, 4, Д), length(О, Д), maplist(бит2, О).
% слова_честны(О): неотвратимо ≤ может быть; -1 у обоих сразу; неполный - неотвратимо 0, может быть не -1
слова_честны(О) :- неотвратимо(О, 1, Н), может_быть(О, 1, М), сходятся(Н, М), неполный_честен(О).
% сходятся(Н, М): Н ≤ М, и -1 у обоих или ни у кого
сходятся(Н, М) :- Н =< М, (Н =:= -1 -> М =:= -1 ; М =\= -1).
% неполный_честен(О): на неполном списке неотвратимо 0, может быть не -1
неполный_честен(О) :- неотвратимо(О, -1, 0), может_быть(О, -1, М), М =\= -1.
% по_старому(О, П, Н, М): определения словами (как в proverka_D2.py) - для сверки с формулами
по_старому(О, 1, 1, 1) :- forall(member(X, О), X =:= 1), !.
по_старому(О, 1, -1, -1) :- forall(member(X, О), X =:= -1), !.
по_старому(_, 1, 0, 1) :- !.
по_старому(О, -1, 0, 1) :- memberchk(1, О), !.
по_старому(_, -1, 0, 0).
