% трое_честно(X, Y, Z): все порядки дают общее значение или 0
трое_честно(X, Y, Z) :- общее(X, Y, Z, О), трое(X, Y, Z, О), трое(Y, Z, X, О).
% общее(X, Y, Z, О): все одинаковы - значение, иначе 0
общее(X, X, X, X) :- !.
общее(_, _, _, 0).

