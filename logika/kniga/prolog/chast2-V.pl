% окошко(A, X, Т): горит (1) только при x = A
окошко(1, X, Т) :- ворота(X, Т).
окошко(-1, X, Т) :- не(X, Н), ворота(Н, Т).
окошко(0, X, Т) :- не_знаю(X, Т).
% сдвиг(X, Т): -1 → 0, 0 → 1, 1 → -1, собран окошками
сдвиг(X, Т) :- окошко(-1, X, A), с_нулём(A, A0), окошко_и_ответ(0, X, 1, B), или(A0, B, Т).
% окошко_и_ответ(A, X, C, Т): окошко для A ∧ ответ C
окошко_и_ответ(A, X, C, Т) :- окошко(A, X, О), и(О, C, Т).
% собрать1(Вектор, X, Т): любая таблица одной буквы окошками - ИЛИ по клеткам (окошко ∧ ответ)
собрать1([A, B, C], X, Т) :- окошко_и_ответ(-1, X, A, Т1), окошко_и_ответ(0, X, B, Т2), окошко_и_ответ(1, X, C, Т3), max_list([Т1, Т2, Т3], Т).
% собрать2(Вектор9, X, Y, Т): любая таблица двух букв окошками
собрать2(В, X, Y, Т) :- findall(Т0, (nth0(К, В, C), клетка(К, A, Б), окошко(A, X, О1), окошко(Б, Y, О2), и(О1, О2, О), и(О, C, Т0)), ТТ), max_list(ТТ, Т).
% клетка(К, A, Б): номер клетки 0..8 - пара значений по порядку -1, 0, 1
клетка(К, A, Б) :- A is К // 3 - 1, Б is К mod 3 - 1.
