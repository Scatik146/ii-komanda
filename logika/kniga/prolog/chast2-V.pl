% ровно_одно(X): из ворота(x), ворота(¬x), не знаю?(x) единица одна
ровно_одно(X) :- ворота(X, A), не(X, Н), три_ответа(A, Н, X).
% три_ответа(A, Н, X): ровно одна единица среди A, ворота(Н), не знаю?(X)
три_ответа(A, Н, X) :- ворота(Н, B), не_знаю(X, C), include(==(1), [A, B, C], [_]).

% Сборка действий с одной буквой: столбец - ответы при x = -1, 0, 1
% собрать_из_x(Действия, С): всё из x, чисел, НЕ и действий двух букв - до неподвижной точки
собрать_из_x(Д, С) :- sort([[-1, 0, 1], [-1, -1, -1], [0, 0, 0], [1, 1, 1]], С0), шаг_сборки(Д, С0, С).
% шаг_сборки(Д, С0, С): добавлять, пока прибавляется
шаг_сборки(Д, С0, С) :- новые(Д, С0, С1), (С1 == С0 -> С = С0 ; шаг_сборки(Д, С1, С)).
% новые(Д, С0, С1): С0 и всё, что из него получается за один шаг
новые(Д, С0, С1) :- findall(Ф, (member(A, С0), maplist(не, A, Ф)), Н1), findall(Ф, (member(Сл, Д), member(A, С0), member(B, С0), maplist(Сл, A, B, Ф)), Н2), append([С0, Н1, Н2], В), sort(В, С1).

