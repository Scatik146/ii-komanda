% подряд_честно(X, A, Б): основание(основание(x, a), b) = основание(x, a ∧ b)
подряд_честно(X, A, Б) :- основание(X, A, Т1), основание(Т1, Б, Т), и(A, Б, AБ), основание(X, AБ, Т).

