% вектор3(В), вектор9(В): все таблицы одной и двух букв
вектор3(В) :- length(В, 3), maplist(тройка, В).
вектор9(В) :- length(В, 9), maplist(тройка, В).
% монотонно1(С), монотонно2(С): больше на входе - не меньше на выходе
монотонно1(С) :- forall((трит(A), трит(B), A =< B), (call(С, A, X), call(С, B, Y), X =< Y)).
монотонно2(С) :- forall((трит(A), трит(B), трит(C), трит(D), A =< C, B =< D), (call(С, A, B, X), call(С, C, D, Y), X =< Y)).
% замок И: из x, y, 0 через НЕ и ворота - всё зависит от одной буквы, а x ∧ y - от двух
пример(в4, 'замок И: без И всё от одной буквы', (собрать_без_и(С), forall(member(Ф, С), одна_буква(Ф)), вектор2(и, ИXY), \+ одна_буква(ИXY))).
% собрать_без_и(С): x, y, 0 и одношаговые НЕ, ворота - до неподвижной точки
собрать_без_и(С) :- вектор_букв(ВX, ВY), sort([ВX, ВY, [0, 0, 0, 0, 0, 0, 0, 0, 0]], С0), без_и_шаг(С0, С).
% вектор_букв(ВX, ВY): столбцы x и y на девяти точках
вектор_букв(ВX, ВY) :- findall(A, (тройка(A), тройка(_)), ВX), findall(B, (тройка(_), тройка(B)), ВY).
% без_и_шаг(С0, С): добавлять НЕ и ворота, пока прибавляется
без_и_шаг(С0, С) :- findall(Ф, (member(A, С0), member(Сл, [не, ворота]), maplist(Сл, A, Ф)), Н), append(С0, Н, В), sort(В, С1), (С1 == С0 -> С = С0 ; без_и_шаг(С1, С)).
% одна_буква(Ф): таблица на девяти точках не меняется по x или не меняется по y
одна_буква(Ф) :- (не_зависит_от_y(Ф) ; не_зависит_от_x(Ф)), !.
% не_зависит_от_y(Ф): в каждой тройке подряд одно значение
не_зависит_от_y([A, A, A, B, B, B, C, C, C]).
% не_зависит_от_x(Ф): три тройки одинаковы
не_зависит_от_x([A, B, C, A, B, C, A, B, C]).
