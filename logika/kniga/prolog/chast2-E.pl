контрпример(е5, 'хватит после 4 пустых', граница(0.5, 0.05, 4)).
пример(е5, 'не искал - не придумывай', придумывать(нет, 0, 5, -1)).
пример(е5, 'порог - придумываю, пометка «наше»', придумывать(нет, 5, 5, 1)).
пример(е5, 'нашлось - собираю', придумывать(да, 8, 5, -1)).
