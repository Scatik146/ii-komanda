% безопасно(НашёлКонтрпример, Полный, Т): «безопасно» = ¬ есть ли контрпример
безопасно(Н, П, Т) :- есть_ли(Н, П, Е), не(Е, Т).
пример(е0, 'до того как влез - 0', безопасно(-1, -1, 0)).
пример(е0, 'после - -1: контрпример ходит на двух ногах', безопасно(1, -1, -1)).
пример(е0, '«убьёт» тоже получило контрпример - -1', безопасно(1, -1, -1)).
пример(е0, 'мои правила: для меня 1 - проверено', основание(1, 1, 1)).
пример(е0, 'для вас 0 - пока не проверите', основание(1, 0, 0)).
контрпример(е0, '«никто не проверял - значит безопасно»', безопасно(-1, -1, 1)).

% === Е.1. Мерфи ===
% датчики: 16 штук, каждый двумя способами
пример(е1, 'монеткой: 2^16 = 65 536 вариантов, все наоборот - один', (Н is 2 ^ 16, Н =:= 65536, findall(В, (length(В, 16), maplist(=(-1), В)), [_]))).
пример(е1, 'один человек с одним убеждением: два варианта - 1 из 2', (findall(В, (бит2(С), length(В, 16), maplist(=(С), В)), ВВ), length(ВВ, 2), include(все_наоборот, ВВ, [_]))).
% все_наоборот(В): все датчики -1
все_наоборот(В) :- forall(member(X, В), X =:= -1).
% закон_мерфи(О, П, Т): из «может пойти не так» делает «пойдёт» - это и есть «может быть»
закон_мерфи(О, П, Т) :- может_быть(О, П, Т).
% готовиться(О, П, Т): готовиться, пока «не так» не исключено - возможно(может быть)
готовиться(О, П, Т) :- может_быть(О, П, М), возможно(М, Т).
% ошибка_мерфи(О): на полном списке закон сказал не то, что «неотвратимо»
ошибка_мерфи(О) :- закон_мерфи(О, 1, З), неотвратимо(О, 1, Н), З =\= Н.
пример(е1, 'полных списков до 4 - 30, закон ошибся в 22', (findall(О, список_до_4(О), ВС), length(ВС, 30), include(ошибка_мерфи, ВС, Ош), length(Ош, 22))).
пример(е1, 'контрпример: один удачный день', (закон_мерфи([1, -1], 1, 1), неотвратимо([1, -1], 1, 0))).
пример(е1, 'неполный список - готовиться всегда', forall(список_до_4(О), готовиться(О, -1, 1))).
пример(е1, 'не готовиться - только если во всех вариантах всё так и список полный', forall((список_до_4(О), готовиться(О, 1, -1)), все_наоборот(О))).
пример(е1, '«всё хорошо» во всех трёх, полный - не готовиться', готовиться([-1, -1, -1], 1, -1)).
контрпример(е1, '«всё хорошо» во всех трёх, неполный - не готовиться', готовиться([-1, -1, -1], -1, -1)).

% === Е.2. Не знаю ===
% Правило 1. Не знаю - значит 0. И остаётся 0, пока не появится основание.
пример(е2, '«всем понятно?» - тишина: основания нет', основание(1, 0, 0)).
пример(е2, 'сказано «не знаю» - при любом основании 0', forall(трит(Б), основание(0, Б, 0))).
контрпример(е2, '«никто не возразил» - 1', основание(1, 0, 1)).
% Правило 2. «Очевидно» - это 0. Покажи пример.
пример(е2, 'компьютер: 0.1 + 0.2 = 0.3 - нет', \+ 0.1 + 0.2 =:= 0.3).
пример(е2, '0.1 + 0.2 = 0.30000000000000004', (X is 0.1 + 0.2, X =:= 0.30000000000000004)).
пример(е2, 'пример показали - вышло -1', основание(-1, 1, -1)).
контрпример(е2, '«очевидно же» без примера - 1', основание(1, 0, 1)).
% Правило 3. Чего нет - того нет.
пример(е2, 'контрольной не было - правило не запускается', срабатывает(отсутствует, -1)).
пример(е2, '0 и -1 - тоже ответы: правило запускается', forall(трит(X), срабатывает(X, 1))).
контрпример(е2, '«отсутствует» - это -1', трит(отсутствует)).
% Правило 4. Не нашёл - не знаю; «нет» - по контрпримеру или полному списку.
пример(е2, 'обошёл всех 25 - без тетради никого: -1', есть_ли(-1, 1, -1)).
пример(е2, 'в куртке ключей нет - про квартиру 0', есть_ли(-1, -1, 0)).
пример(е2, 'есть ли: вектор (0, -1, 1, 1)', findall(Т, (бит2(Н), бит2(П), есть_ли(Н, П, Т)), [0, -1, 1, 1])).
контрпример(е2, '«нет записи - значит был»', есть_ли(-1, -1, -1)).
% Правило 5. «Не нашли» не значит «нет» - високосный год.
% високосный_просто(Г): «очевидно, каждый четвёртый»
високосный_просто(Г) :- Г mod 4 =:= 0.
% високосный(Г): по григорианскому календарю
високосный(Г) :- Г mod 400 =:= 0, !.
високосный(Г) :- Г mod 4 =:= 0, Г mod 100 =\= 0.
% ошибка_года(Г): простая программа ошибается на годе Г
ошибка_года(Г) :- високосный_просто(Г), \+ високосный(Г).
ошибка_года(Г) :- високосный(Г), \+ високосный_просто(Г).
пример(е2, '2020, 2023, 2024 - ошибок не нашли: 0', (\+ (member(Г, [2020, 2023, 2024]), ошибка_года(Г)), есть_ли(-1, -1, 0))).
пример(е2, '1900 - ошибка найдена: 1', (ошибка_года(1900), есть_ли(1, -1, 1))).
пример(е2, '2000 - високосный', високосный(2000)).
контрпример(е2, 'три теста прошли - «ошибок нет»: -1', есть_ли(-1, -1, -1)).
% Правило 6. На всё три ответа: да - делаю, нет - не делаю, не знаю - ищу.
% действие(X, Что): делаю = ворота(x), ищу = не знаю?(x), не делаю = ворота(¬x)
действие(X, делаю) :- ворота(X, 1).
действие(X, ищу) :- не_знаю(X, 1).
действие(X, не_делаю) :- не(X, Н), ворота(Н, 1).
пример(е2, 'на каждый трит - ровно одно действие', forall(трит(X), findall(Ч, действие(X, Ч), [_]))).
пример(е2, 'флешка проверена? не знаю - ищу', действие(0, ищу)).
пример(е2, 'векторы: делаю (-1,-1,1), ищу (-1,1,-1), не делаю (1,-1,-1)', (вектор1(ворота, [-1, -1, 1]), вектор1(не_знаю, [-1, 1, -1]), вектор1(ворота_не, [1, -1, -1]))).
контрпример(е2, '«не знаю - ну и ладно, возьму»', действие(0, делаю)).
% ворота_не(X, Т): ворота(¬x)
ворота_не(X, Т) :- не(X, Н), ворота(Н, Т).
% Правило 7. Не знаю - так и говорю: «пока не знаю, проверю».
% говорю(X, Слова): да, нет, пока не знаю - из тех же ворот
говорю(X, да) :- действие(X, делаю).
говорю(X, нет) :- действие(X, не_делаю).
говорю(X, пока_не_знаю_проверю) :- действие(X, ищу).
пример(е2, '0 - «пока не знаю, проверю»', говорю(0, пока_не_знаю_проверю)).
пример(е2, '-1 - «нет», 1 - «да»', (говорю(-1, нет), говорю(1, да))).
контрпример(е2, '«наверное, да» на 0', говорю(0, да)).
% Правило 8. Пересказ - это 0. Читаю подлинник.
пример(е2, 'пересказ (подлинник = -1) - 0, что бы ни сказали', forall(трит(X), основание(X, -1, 0))).
пример(е2, 'подлинник - что сказано', forall(трит(X), основание(X, 1, X))).
контрпример(е2, 'по пересказу - 1', основание(1, -1, 1)).
% Правило 9. Двое спорят - пишу «не знаю» и запоминаю, кто и почему.
% спор(Голоса, Т, За-Всего): согласие всех и подпись
спор(Г, Т, За-Всего) :- согласие_всех(Г, Т), include(==(1), Г, ЗЗ), length(ЗЗ, За), length(Г, Всего).
пример(е2, 'часы: 8:00 и 8:05 - 0', согласие(1, -1, 0)).
пример(е2, 'три словаря «да», один «нет» - 0 и «3 из 4»', спор([1, 1, 1, -1], 0, 3-4)).
пример(е2, 'четыре «да» - 1', спор([1, 1, 1, 1], 1, 4-4)).
пример(е2, '«не знаю» и «да» - не знаю', согласие(0, 1, 0)).
контрпример(е2, 'по большинству - 1', спор([1, 1, 1, -1], 1, _)).
% Правило 10 (ОЧ-33). «Нет» говорю, только когда закрыты все лазейки.
пример(е2, 'подтвердить: вектор (-1,0,0,0,0,0,1,1,1)', вектор2(подтвердить, [-1, 0, 0, 0, 0, 0, 1, 1, 1])).
пример(е2, 'есть ли = подтвердить(нашёл, ¬полный)', forall((бит2(Н), бит2(П)), (есть_ли(Н, П, Т), не(П, НП), подтвердить(Н, НП, Т)))).
пример(е2, 'основание = подтвердить(x ∧ b, ¬b)', forall((трит(X), трит(Б)), (основание(X, Б, Т), и(X, Б, A), не(Б, НБ), подтвердить(A, НБ, Т)))).
пример(е2, 'согласие = подтвердить(x ∧ y, x ∨ y)', forall((трит(X), трит(Y)), (согласие(X, Y, Т), и(X, Y, A), или(X, Y, Л), подтвердить(A, Л, Т)))).
пример(е2, 'телефон: искал не везде - 0', подтвердить(-1, 1, 0)).
пример(е2, 'телефон: обошёл всё по списку - -1', подтвердить(-1, -1, -1)).
контрпример(е2, '«в кармане нет - значит, потерял»', подтвердить(-1, 1, -1)).

% === Е.3. Проверено и ворота ===
% Правило 1 (ОЧ-02). У всего два вопроса: правда ли и проверено ли.
% одним_тритом(П, Пр, Т): контрпример - проверку выбросили
одним_тритом(П, _, П).
пример(е3, 'пар (правда, проверено) - 9', (findall(П-Пр, пара(П, Пр), ВП), length(ВП, 9))).
пример(е3, 'одним тритом: вектор (-1,-1,-1,0,0,0,1,1,1)', вектор2(одним_тритом, [-1, -1, -1, 0, 0, 0, 1, 1, 1])).
пример(е3, 'одним тритом «да, проверено» = «да, не проверял»', (одним_тритом(1, 1, Т), одним_тритом(1, -1, Т))).
контрпример(е3, 'одним тритом проверку видно', (одним_тритом(1, 1, A), одним_тритом(1, -1, B), A =\= B)).
% Правило 2 (ОЧ-03). проверено(Р, С, Т) = р ∧ основание(р, с)
проверено(Р, С, Т) :- основание(Р, С, О), и(Р, О, Т).
пример(е3, 'проверено: вектор (-1,-1,-1,0,0,0,0,0,1)', вектор2(проверено, [-1, -1, -1, 0, 0, 0, 0, 0, 1])).
пример(е3, 'билеты в черновике - -1', проверено(-1, 1, -1)).
пример(е3, 'решил, но до пятницы - 0', проверено(1, -1, 0)).
контрпример(е3, '«проверено» без срока - 1', проверено(1, 0, 1)).
% Правило 3 (ОЧ-06). нести(Н, Г, Т) = ворота(н) ∧ возможно(г)
нести(Н, Г, Т) :- ворота(Н, A), возможно(Г, B), и(A, B, Т).
пример(е3, 'нести: вектор (-1,-1,-1,-1,-1,-1,-1,1,1)', вектор2(нести, [-1, -1, -1, -1, -1, -1, -1, 1, 1])).
пример(е3, 'сам проверил - несу', нести(1, 0, 1)).
контрпример(е3, 'черновик - знатоку', нести(1, -1, 1)).
% Правило 4 (Б5). тревога(Н, Ч, Т) = ворота(н) ∧ ¬ворота(ч); 1 - ошибка
тревога(Н, Ч, Т) :- ворота(Н, A), ворота(Ч, B), не(B, НБ), и(A, НБ, Т).
пример(е3, 'тревога: вектор (-1,-1,-1,-1,-1,-1,1,1,-1)', вектор2(тревога, [-1, -1, -1, -1, -1, -1, 1, 1, -1])).
пример(е3, '«не знаю, смотрел ли кто-то» - тревога', тревога(1, 0, 1)).
контрпример(е3, 'автор сам себе проверяющий: чужой нет, а тревоги нет', тревога(1, -1, -1)).
% Правило 5 (ОЧ-19). экспертиза(X, В, З, Т) = (н ∧ основание(в, з)) ∨ (¬н ∧ x), н = не знаю?(x)
экспертиза(X, В, З, Т) :- не_знаю(X, Н), основание(В, З, О), и(Н, О, A), не(Н, НН), и(НН, X, B), или(A, B, Т).
% экспертиза_словами(X, В, З, Т): был ответ - не трогаем; был 0 - вердикт, если независима
экспертиза_словами(X, _, _, X) :- X =\= 0.
экспертиза_словами(0, В, 1, В).
экспертиза_словами(0, _, З, 0) :- З =\= 1.
пример(е3, 'экспертиза: все 27 наборов совпали со словами', forall((трит(X), трит(В), трит(З)), (экспертиза(X, В, З, Т), экспертиза_словами(X, В, З, Т)))).
пример(е3, 'коллега нашёл два ответа - -1', экспертиза(0, -1, 1, -1)).
пример(е3, 'ответ уже был - не трогаем', экспертиза(1, -1, 1, 1)).
контрпример(е3, 'друг сказал «да» - 1', экспертиза(0, 1, -1, 1)).
% Правило 6 (ОЧ-04). и_по_частям(Части, Т): И по всем частям
и_по_частям(Ч, Т) :- foldl(и, Ч, 1, Т).
пример(е3, 'урок (1,1,0,1,1) - 0', и_по_частям([1, 1, 0, 1, 1], 0)).
пример(е3, 'урок (1,1,-1,1,1) - -1', и_по_частям([1, 1, -1, 1, 1], -1)).
контрпример(е3, 'одна часть -1, урок «почти готов» - 0', и_по_частям([1, 1, -1, 1, 1], 0)).
% Правило 7 (ОЧ-05). наружу - из А.2: ворота(п ∧ пр)
пример(е3, 'наружу: вектор (-1 восемь раз, 1)', вектор2(наружу, [-1, -1, -1, -1, -1, -1, -1, -1, 1])).
контрпример(е3, '(1, 0) - наружу', наружу(1, 0, 1)).
% Правило 8 (Б1). пропустить(X, Пр, Т) = ворота(основание(x, пр))
пропустить(X, Пр, Т) :- основание(X, Пр, О), ворота(О, Т).
пример(е3, 'пропустить - та же таблица, что наружу', (вектор2(пропустить, В), вектор2(наружу, В))).
контрпример(е3, '«сам посмотрю» - проверку не запускали', пропустить(1, 0, 1)).
% Правило 9 (ОЧ-12). включить = ворота(з); правило 10 (ОЧ-16). прочерк = ворота(¬о)
включить(З, Т) :- ворота(З, Т).
прочерк(О, Т) :- не(О, Н), ворота(Н, Т).
пример(е3, 'включить: (-1,-1,1)', вектор1(включить, [-1, -1, 1])).
пример(е3, 'прочерк: (1,-1,-1)', вектор1(прочерк, [1, -1, -1])).
контрпример(е3, 'порог не задан - «по умолчанию» включить', включить(0, 1)).
контрпример(е3, 'не решил - прочерк «пока» принять', прочерк(0, 1)).
% Правило 11 (ОЧ-17). Ворота склеивают «нет» и «не знаю»
пример(е3, 'ворота(0) = ворота(-1)', (ворота(0, Т), ворота(-1, Т))).
контрпример(е3, 'по ответу ворот видно, был ли 0', (ворота(0, A), ворота(-1, B), A =\= B)).
% Правило 12 (ОЧ-31). усомниться(X, С, Т) = основание(x, ¬с)
усомниться(X, С, Т) :- не(С, НС), основание(X, НС, Т).
пример(е3, 'усомниться: вектор (-1,0,0,0,0,0,1,0,0)', вектор2(усомниться, [-1, 0, 0, 0, 0, 0, 1, 0, 0])).
пример(е3, 'после сомнения ворота закрыты', forall((трит(X), member(С, [0, 1])), (усомниться(X, С, У), ворота(У, -1)))).
контрпример(е3, '«ИИ сказал - значит, да»', усомниться(1, 1, 1)).
% Правило 13 (Б8). можно(О, Р, Т) = ворота(о) ∨ ворота(р)
можно(О, Р, Т) :- ворота(О, A), ворота(Р, B), или(A, B, Т).
пример(е3, 'можно: вектор (-1,-1,1,-1,-1,1,1,1,1)', вектор2(можно, [-1, -1, 1, -1, -1, 1, 1, 1, 1])).
контрпример(е3, '«наверное, отменяемо» - можно', можно(0, 0, 1)).

