% Правило 6 (ОЧ-21). собирать = ворота(е), с нуля = ворота(¬е), искать = не знаю?(е)
собирать(Е, Т) :- ворота(Е, Т).
с_нуля(Е, Т) :- не(Е, Н), ворота(Н, Т).
искать(Е, Т) :- не_знаю(Е, Т).
пример(е5, 'собирать (-1,-1,1), с нуля (1,-1,-1), искать (-1,1,-1)', (вектор1(собирать, [-1, -1, 1]), вектор1(с_нуля, [1, -1, -1]), вектор1(искать, [-1, 1, -1]))).
пример(е5, 'всегда ровно одно', forall(трит(Е), (собирать(Е, A), с_нуля(Е, B), искать(Е, C), include(=:=(1), [A, B, C], [_])))).
контрпример(е5, '«быстрее написать самому», когда части есть', с_нуля(1, 1)).
% Правило 7 (ОЧ-22). есть_где_то(Найдено, Пустых, Порог, Т); усталости среди входов нет
есть_где_то(да, _, _, 1) :- !.
есть_где_то(нет, П, Пр, -1) :- П >= Пр, !.
есть_где_то(нет, _, _, 0).
придумывать(Н, П, Пр, Т) :- есть_где_то(Н, П, Пр, Е), не(Е, НЕ), ворота(НЕ, Т).
% граница(Находит, Ошибка, К): наименьшее К, при котором (1 - находит)^К =< ошибка (Вальд)
граница(Н, О, К) :- between(0, 100, К), (1 - Н) ** К =< О, !.
