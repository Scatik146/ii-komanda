% === А.0. Почему три ===
% пара(Сказано, Верить): два трита - что сказано и насколько верить
пара(С, В) :- трит(С), трит(В).
% бит_как_пара(Бит, С, В): бит части 1 - пара части 2
бит_как_пара(1, 1, 1).
бит_как_пара(0, -1, 1).
пример(а0, 'два трита - девять вариантов', (findall(С-В, пара(С, В), П), length(П, 9))).
пример(а0, 'бит 1 - (1, 1): да, и верю', бит_как_пара(1, 1, 1)).
пример(а0, 'бит 0 - (-1, 1): нет, и верю', бит_как_пара(0, -1, 1)).
контрпример(а0, 'бит 0 - «всё, что не (1, 1)»: (0, 1)', бит_как_пара(0, 0, 1)).

% === А.1. НЕ, И, ИЛИ на тритах ===
пример(а1, '¬0 = 0', не(0, 0)).
пример(а1, '¬(-1) = 1', не(-1, 1)).
пример(а1, 'экскурсия: 1 ∧ ¬0 = 0', (не(0, Н), и(1, Н, 0))).
пример(а1, 'перенос: -1 ∨ 0 = 0', или(-1, 0, 0)).
пример(а1, '1 ∨ 0 = 1', или(1, 0, 1)).
пример(а1, '-1 ∧ 0 = -1', и(-1, 0, -1)).
% старые формулы части 1 на тритах ошибаются
контрпример(а1, '1 - x: ¬0 = 1', не(0, 1)).
контрпример(а1, '1 - x: ¬1 = 0', не(1, 0)).
контрпример(а1, 'x · y: -1 ∧ -1 = 1', и(-1, -1, 1)).
контрпример(а1, 'x · y: 0 ∧ -1 = 0', и(0, -1, 0)).
контрпример(а1, 'x + y - xy: -1 ∨ -1 = -3', или(-1, -1, -3)).
% на битах (-1 и 1) - те же И и ИЛИ части 1
бит2(-1).
бит2(1).
пример(а1, 'на битах ∧ - меньшее, ∨ - большее', forall((бит2(X), бит2(Y)), (и(X, Y, A), A =:= min(X, Y), или(X, Y, B), B =:= max(X, Y)))).

% === А.2. Девять вариантов в деле ===
% вместе(С, В, Т): сказано ∧ верить
вместе(С, В, Т) :- и(С, В, Т).
% наружу(С, В, Т): ворота(сказано ∧ верить)
наружу(С, В, Т) :- вместе(С, В, A), ворота(A, Т).
пример(а2, 'учитель записал (1, 1) - наружу', наружу(1, 1, 1)).
пример(а2, 'учитель: «не будет» (-1, 1) - «будет» не наружу', наружу(-1, 1, -1)).
пример(а2, '«контрольной нет»: (¬(-1), 1) - наружу', (не(-1, Н), наружу(Н, 1, 1))).
пример(а2, 'соседка: -1 ∧ -1 = -1', вместе(-1, -1, -1)).
пример(а2, '«ещё не решил» (0, 1) - не наружу', наружу(0, 1, -1)).
пример(а2, 'наружу - только (1, 1)', (findall(С-В, (пара(С, В), наружу(С, В, 1)), [1-1]))).
пример(а2, 'прямо или через НЕ - две пары', (findall(С-В, (пара(С, В), (наружу(С, В, 1) ; (не(С, Н), наружу(Н, В, 1)))), П), msort(П, [-1-1, 1-1]))).
контрпример(а2, '«верю, значит да»: (-1, 1) наружу', наружу(-1, 1, 1)).
контрпример(а2, '«сказали, значит да»: (1, 0) наружу', наружу(1, 0, 1)).
контрпример(а2, 'умножение: (-1)·(-1) = 1 наружу', наружу(-1, -1, 1)).
