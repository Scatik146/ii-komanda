% bazis.pl — слова части 2 «Трит» на SWI-Prolog, снизу вверх (Марьям, 21.11.2026)
% Основной базис тритов: {и, не, ворота, 0}. Всё остальное собрано только из уже собранных слов.
% Проверка: node logika/kniga/prolog/zapusk.cjs <путь к drakon-graf/site/experiments/prolog/lib>
% У каждого слова - пример и контрпример (пример/3, контрпример/3).

:- discontiguous пример/3, контрпример/3.
:- multifile пример/3, контрпример/3.

% === 0. Трит ===
% трит(X, Имя): 1 - да, 0 - не знаю, -1 - нет
трит(1, да).
трит(0, не_знаю).
трит(-1, нет).
% трит(X): X - трит (для перебора)
трит(X) :- трит(X, _).
пример(базис, 'трит(0) - не знаю', трит(0, не_знаю)).
контрпример(базис, '2 - не трит', трит(2)).

% === 1. Нижний уровень - основной базис ===
% не(X, Y): меняет знак
не(X, Y) :- Y is -X.
пример(базис, '¬(-1) = 1', не(-1, 1)).
контрпример(базис, '¬0 = 1 (старое 1 - x)', не(0, 1)).

% и(X, Y, Z): берёт меньшее
и(X, Y, Z) :- Z is min(X, Y).
пример(базис, '1 ∧ 0 = 0', и(1, 0, 0)).
контрпример(базис, '-1 ∧ -1 = 1 (умножение)', и(-1, -1, 1)).

% ворота(X, Т): пропускают только 1
ворота(1, 1).
ворота(X, -1) :- X =\= 1.
пример(базис, 'ворота(1) = 1', ворота(1, 1)).
контрпример(базис, 'ворота(0) = 1', ворота(0, 1)).

% ноль(X): число «не знаю»
ноль(0).
пример(базис, 'ноль - 0', ноль(0)).
контрпример(базис, 'ноль - не 1', ноль(1)).

% === 2. Следующий уровень ===
% не_и(X, Y, Z): ¬(x ∧ y)
не_и(X, Y, Z) :- и(X, Y, A), не(A, Z).
пример(уровень_1, '¬(1 ∧ 1) = -1', не_и(1, 1, -1)).
контрпример(уровень_1, '¬(1 ∧ -1) = -1', не_и(1, -1, -1)).

% или(X, Y, Z): x ∨ y = ¬(¬x ∧ ¬y) - берёт большее
или(X, Y, Z) :- не(X, A), не(Y, B), не_и(A, B, Z).
пример(уровень_1, '-1 ∨ 0 = 0', или(-1, 0, 0)).
контрпример(уровень_1, '-1 ∨ 0 = -1', или(-1, 0, -1)).

% погасло(X, Т): ¬ворота(x)
погасло(X, Т) :- ворота(X, A), не(A, Т).
пример(уровень_1, '¬ворота(0) = 1', погасло(0, 1)).
контрпример(уровень_1, '¬ворота(1) = 1', погасло(1, 1)).

% погасли_оба(A, X, Т): A ∧ ¬ворота(x)
погасли_оба(A, X, Т) :- погасло(X, B), и(A, B, Т).
пример(уровень_1, '1 ∧ ¬ворота(0) = 1', погасли_оба(1, 0, 1)).
контрпример(уровень_1, '1 ∧ ¬ворота(1) = 1', погасли_оба(1, 1, 1)).

% не_знаю(X, Т): пропускает только 0: ¬ворота(x) ∧ ¬ворота(¬x)
не_знаю(X, Т) :- погасло(X, A), не(X, НеX), погасли_оба(A, НеX, Т).
пример(уровень_1, 'не знаю?(0) = 1', не_знаю(0, 1)).
контрпример(уровень_1, 'не знаю?(1) = 1', не_знаю(1, 1)).

% возможно(X, Т): ¬ворота(¬x) - всё, кроме -1
возможно(X, Т) :- не(X, НеX), погасло(НеX, Т).
пример(уровень_1, 'возможно(0) = 1', возможно(0, 1)).
контрпример(уровень_1, 'возможно(-1) = 1', возможно(-1, 1)).

% с_нулём(X, Z): x ∧ 0
с_нулём(X, Z) :- ноль(Н), и(X, Н, Z).
пример(уровень_1, '1 ∧ 0 = 0', с_нулём(1, 0)).
контрпример(уровень_1, '-1 ∧ 0 = 0', с_нулём(-1, 0)).

% или_ноль(A, Y, Z): A ∨ (y ∧ 0) - общий хвост основания, согласия и «есть ли»
или_ноль(A, Y, Z) :- с_нулём(Y, C), или(A, C, Z).
пример(уровень_1, '-1 ∨ (1 ∧ 0) = 0', или_ноль(-1, 1, 0)).
контрпример(уровень_1, '-1 ∨ (-1 ∧ 0) = 0', или_ноль(-1, -1, 0)).

% === 3. Действия ===
% основание(X, Б, Z): (x ∧ b) ∨ (¬b ∧ 0) - есть основание - x, нет - 0
основание(X, Б, Z) :- и(X, Б, A), не(Б, НеБ), или_ноль(A, НеБ, Z).
пример(действия, 'основание(-1, 1) = -1', основание(-1, 1, -1)).
контрпример(действия, 'основание(1, 0) = 1', основание(1, 0, 1)).

% согласие(X, Y, Z): (x ∧ y) ∨ ((x ∨ y) ∧ 0) - одинаково - значение, разное - 0
согласие(X, Y, Z) :- и(X, Y, A), или(X, Y, O), или_ноль(A, O, Z).
пример(действия, 'согласие(1, 1) = 1', согласие(1, 1, 1)).
контрпример(действия, 'согласие(1, -1) = 1', согласие(1, -1, 1)).

% есть_ли(Нашёл, Полный, Т): нашёл ∨ (¬полный ∧ 0); нашёл, полный - 1 или -1
есть_ли(Нашёл, Полный, Т) :- не(Полный, НеП), или_ноль(Нашёл, НеП, Т).
пример(действия, 'не нашёл, список полный - -1', есть_ли(-1, 1, -1)).
контрпример(действия, 'не нашёл, список неполный - -1', есть_ли(-1, -1, -1)).

% срабатывает(X, Т): по «отсутствует» правило не запускается; отдельное слово нижнего уровня
срабатывает(отсутствует, -1).
срабатывает(X, 1) :- трит(X).
пример(действия, 'срабатывает(0) = 1', срабатывает(0, 1)).
контрпример(действия, 'срабатывает(отсутствует) = 1', срабатывает(отсутствует, 1)).

% === 4. Таблицы и векторы ===
% вектор1(Слово, В): ответы слова с одной буквой при x = -1, 0, 1
вектор1(Слово, В) :- findall(Т, (тройка(X), call(Слово, X, Т)), В).
% вектор2(Слово, В): девять ответов слова с двумя буквами, строка за строкой
вектор2(Слово, В) :- findall(Т, (тройка(X), тройка(Y), call(Слово, X, Y, Т)), В).
% тройка(X): триты по порядку -1, 0, 1
тройка(-1).
тройка(0).
тройка(1).
пример(таблицы, 'не (1, 0, -1)', вектор1(не, [1, 0, -1])).
пример(таблицы, 'и (-1,-1,-1,-1,0,0,-1,0,1)', вектор2(и, [-1, -1, -1, -1, 0, 0, -1, 0, 1])).
пример(таблицы, 'или (-1,0,1,0,0,1,1,1,1)', вектор2(или, [-1, 0, 1, 0, 0, 1, 1, 1, 1])).
пример(таблицы, 'ворота (-1,-1,1)', вектор1(ворота, [-1, -1, 1])).
пример(таблицы, 'не знаю? (-1,1,-1)', вектор1(не_знаю, [-1, 1, -1])).
пример(таблицы, 'возможно (-1,1,1)', вектор1(возможно, [-1, 1, 1])).
пример(таблицы, 'основание (0,0,-1,0,0,0,0,0,1)', вектор2(основание, [0, 0, -1, 0, 0, 0, 0, 0, 1])).
пример(таблицы, 'согласие (-1,0,0,0,0,0,0,0,1)', вектор2(согласие, [-1, 0, 0, 0, 0, 0, 0, 0, 1])).
контрпример(таблицы, 'или - не как и', вектор2(или, [-1, -1, -1, -1, 0, 0, -1, 0, 1])).

% === 5. Проверка ===
% плохой(Шаг, Что): пример не выводится или контрпример выводится
плохой(Шаг, Что) :- пример(Шаг, Что, Цель), \+ call(Цель).
плохой(Шаг, Что) :- контрпример(Шаг, Что, Цель), call(Цель).
% всего(Шаг, Н): сколько примеров и контрпримеров у шага
всего(Шаг, Н) :- findall(x, (пример(Шаг, _, _) ; контрпример(Шаг, _, _)), Х), length(Х, Н).
% шаги(Шаги): все шаги по порядку появления
шаги(Шаги) :- findall(Ш, (пример(Ш, _, _) ; контрпример(Ш, _, _)), Ш0), list_to_set(Ш0, Шаги).
% итог(Шаг, Н, Плохие): всего и список ошибок
итог(Шаг, Н, Плохие) :- всего(Шаг, Н), findall(Ч, плохой(Шаг, Ч), Плохие).
