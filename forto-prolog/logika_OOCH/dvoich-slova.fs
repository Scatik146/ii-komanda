\ Двоичная логика на Форте: векторы как числа (Марьям, 19.11.2026)
\ Вектор функции — число: f(0,0) f(0,1) f(1,0) f(1,1) — старший разряд первым.
\ Законы — в dvoich-zakony.fs (собирает dvoich.py). Проверка: node proverka-dvoich.cjs <forth-lib> <prolog-lib>

\ === 0. Бит и векторы переменных ===
\ Бит — двоичная цифра: 0 или 1. Вектор переменной — её значения во всех строках таблицы.
VARIABLE маска                                  \ единицы во всю длину вектора
255 маска !                                     \ по умолчанию — три переменные, 8 строк
15 CONSTANT X   51 CONSTANT Y   85 CONSTANT Z  \ x = 00001111, y = 00110011, z = 01010101
255 CONSTANT ВСЕ                                \ вектор константы 1

\ === 1. Действия над векторами — сразу во всех строках таблицы ===
: И        ( a b -- c )   AND ;
: ИЛИ      ( a b -- c )   OR ;
: НЕ       ( a -- b )     INVERT маска @ AND ;
: ИСКЛ     ( a b -- c )   XOR ;                 \ исключающее ИЛИ: сложение по модулю 2
: ИМПЛ     ( a b -- c )   SWAP НЕ ИЛИ ;         \ x → y = ¬x ∨ y
: ЭКВ      ( a b -- c )   ИСКЛ НЕ ;
: ШЕФФЕР   ( a b -- c )   И НЕ ;
: ПИРС     ( a b -- c )   ИЛИ НЕ ;

\ === 2. Функция по номеру: f_n от двух векторов ===
VARIABLE номер   VARIABLE иксы   VARIABLE игреки
: бит>маска  ( n i -- m )  RSHIFT 1 AND NEGATE ;          \ бит номера → «все единицы» или 0
: член       ( a b i -- t ) номер @ SWAP бит>маска AND AND ;
: f-вект     ( X Y n -- R ) номер ! игреки ! иксы !
             иксы @ НЕ  игреки @ НЕ  3 член
             иксы @ НЕ  игреки @     2 член ИЛИ
             иксы @     игреки @ НЕ  1 член ИЛИ
             иксы @     игреки @     0 член ИЛИ ;
: в-ширине   ( X Y n w -- R ) маска @ >R маска ! f-вект R> маска ! ;
: f2         ( X Y n -- R ) 15 в-ширине ;               \ две переменные: 3 5 n f2 → n
: f3         ( X Y n -- R ) 255 в-ширине ;              \ три переменные: z фиктивная

\ === 3. Полином Жегалкина: сдвиг и маска — вектор переменной ===
: шаг        ( v маска сдвиг -- v ) >R OVER R> RSHIFT AND XOR ;
: жегалкин2  ( v -- коэф ) 5 1 шаг  3 2 шаг ;                    \ туда и обратно — одно и то же
: жегалкин3  ( v -- коэф ) 85 1 шаг  51 2 шаг  15 4 шаг ;

\ === 4. Число членов СДНФ — число единиц в векторе ===
: единиц     ( v -- n ) 0 SWAP BEGIN DUP WHILE DUP 1 AND ROT + SWAP 1 RSHIFT REPEAT DROP ;
