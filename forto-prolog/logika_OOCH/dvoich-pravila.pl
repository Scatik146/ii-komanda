% Двоичная логика на SWI-Prolog: формулы (Марьям, 19.11.2026)
% Формула — терм: x, y, z, 0, 1, не(А), и(А, Б), или(А, Б), импл(А, Б), экв(А, Б), искл(А, Б), шеффер(А, Б), пирс(А, Б).
% Базисы, законы и имена функций — в dvoich-dannye.pl (собирает dvoich.py).
% Проверка: node proverka-dvoich.cjs <forth-lib> <prolog-lib>

% === 0. Бит ===

% бит(Б): Б — двоичная цифра
% пример: бит(1).  контрпример: бит(2).
бит(0).
бит(1).

% === 1. Значение формулы на наборе ===

% знач(Формула, Набор, З): значение формулы, Набор — список вида [x-1, y-0]
% пример: знач(и(x, y), [x-1, y-0], 0).  контрпример: знач(или(x, y), [x-1, y-0], 0).
знач(0, _, 0).
знач(1, _, 1).
знач(П, Набор, З) :- atom(П), memberchk(П-З, Набор).
знач(не(А), Н, З) :- знач(А, Н, ЗА), З is 1 - ЗА.
знач(и(А, Б), Н, З) :- знач(А, Н, ЗА), знач(Б, Н, ЗБ), З is min(ЗА, ЗБ).
знач(или(А, Б), Н, З) :- знач(А, Н, ЗА), знач(Б, Н, ЗБ), З is max(ЗА, ЗБ).
знач(импл(А, Б), Н, З) :- знач(А, Н, ЗА), знач(Б, Н, ЗБ), З is max(1 - ЗА, ЗБ).
знач(экв(А, Б), Н, З) :- знач(А, Н, ЗА), знач(Б, Н, ЗБ), З is 1 - abs(ЗА - ЗБ).
знач(искл(А, Б), Н, З) :- знач(А, Н, ЗА), знач(Б, Н, ЗБ), З is abs(ЗА - ЗБ).
знач(шеффер(А, Б), Н, З) :- знач(А, Н, ЗА), знач(Б, Н, ЗБ), З is 1 - min(ЗА, ЗБ).
знач(пирс(А, Б), Н, З) :- знач(А, Н, ЗА), знач(Б, Н, ЗБ), З is 1 - max(ЗА, ЗБ).

% === 2. Вектор формулы и номер функции ===

% вектор2(Формула, В): значения f(0,0) f(0,1) f(1,0) f(1,1)
% пример: вектор2(импл(x, y), [1, 1, 0, 1]).  контрпример: вектор2(импл(x, y), [1, 0, 1, 1]).
вектор2(Ф, В) :- findall(З, (бит(X), бит(Y), знач(Ф, [x-X, y-Y], З)), В).

% вектор3(Формула, В): то же для трёх переменных
% пример: вектор3(x, [0, 0, 0, 0, 1, 1, 1, 1]).  контрпример: вектор3(z, [0, 0, 0, 0, 1, 1, 1, 1]).
вектор3(Ф, В) :- findall(З, (бит(X), бит(Y), бит(Z), знач(Ф, [x-X, y-Y, z-Z], З)), В).

% номер(Вектор, Н): вектор как двоичное число
% пример: номер([1, 1, 0, 1], 13).  контрпример: номер([1, 1, 0, 1], 11).
номер(В, Н) :- foldl(разряд, В, 0, Н).

% разряд(Б, Было, Стало): дописать бит справа
% пример: разряд(1, 6, 13).  контрпример: разряд(1, 6, 12).
разряд(Б, Было, Стало) :- Стало is 2 * Было + Б.

% функция_формулы(Формула, Н): какая из 16 функций записана формулой
% пример: функция_формулы(или(не(x), y), 13).  контрпример: функция_формулы(или(не(x), y), 7).
функция_формулы(Ф, Н) :- вектор2(Ф, В), номер(В, Н).

% упростить(Формула, Имя): любую формулу двух переменных — до имени одной из 16 функций
% пример: упростить(и(импл(x, y), импл(y, x)), 'эквивалентность').  контрпример: упростить(или(x, не(x)), 'константа 0').
упростить(Ф, Имя) :- функция_формулы(Ф, Н), имя_функции(Н, Имя).

% === 3. СДНФ и СКНФ: из вектора и обратно ===

% разложить(К, X, Y): номер строки → значения x и y
% пример: разложить(2, 1, 0).  контрпример: разложить(2, 0, 1).
разложить(К, X, Y) :- X is К // 2, Y is К mod 2.

% литерал(П, Б, Л): для СДНФ — П при 1, не(П) при 0
% пример: литерал(x, 0, не(x)).  контрпример: литерал(x, 1, не(x)).
литерал(П, 1, П).
литерал(П, 0, не(П)).

% минтерм(В, М): конъюнкция для строки, где в векторе 1
% пример: минтерм([0, 0, 0, 1], и(x, y)).  контрпример: минтерм([0, 0, 0, 1], и(x, не(y))).
минтерм(В, и(ЛX, ЛY)) :- nth0(К, В, 1), разложить(К, X, Y), литералы(X, Y, ЛX, ЛY).

% литералы(X, Y, ЛX, ЛY): литералы СДНФ для пары значений
% пример: литералы(1, 0, x, не(y)).  контрпример: литералы(1, 0, x, y).
литералы(X, Y, ЛX, ЛY) :- литерал(x, X, ЛX), литерал(y, Y, ЛY).

% макстерм(В, М): дизъюнкция для строки, где в векторе 0 (литералы наоборот)
% пример: макстерм([1, 1, 0, 1], или(не(x), y)).  контрпример: макстерм([1, 1, 0, 1], или(x, y)).
макстерм(В, или(ЛX, ЛY)) :- nth0(К, В, 0), разложить(К, X, Y), литералы_кнф(X, Y, ЛX, ЛY).

% литералы_кнф(X, Y, ЛX, ЛY): в СКНФ переменная берётся с отрицанием при 1
% пример: литералы_кнф(1, 0, не(x), y).  контрпример: литералы_кнф(1, 0, x, y).
литералы_кнф(X, Y, ЛX, ЛY) :- НX is 1 - X, НY is 1 - Y, литералы(НX, НY, ЛX, ЛY).

% сднф(В, Ф): совершенная ДНФ по вектору;  скнф(В, Ф): совершенная КНФ
% пример: сднф([0, 0, 0, 1], и(x, y)).  контрпример: сднф([0, 0, 0, 0], и(x, y)).
сднф(В, Ф) :- findall(М, минтерм(В, М), Мс), собрать(или, 0, Мс, Ф).
скнф(В, Ф) :- findall(М, макстерм(В, М), Мс), собрать(и, 1, Мс, Ф).

% собрать(Связка, Пусто, Список, Ф): соединить список связкой; пустой — константа
% пример: собрать(или, 0, [x, y], или(x, y)).  контрпример: собрать(или, 0, [], 1).
собрать(_, Пусто, [], Пусто).
собрать(_, _, [М], М).
собрать(С, П, [М, Н | Ост], Ф) :- собрать(С, П, [Н | Ост], Хвост), Ф =.. [С, М, Хвост].

% сднф_скнф_обратно(В): из вектора в СДНФ и СКНФ — и обратно в тот же вектор
% пример: сднф_скнф_обратно([1, 1, 0, 1]).  контрпример: нет — должно выполняться для всех 16.
сднф_скнф_обратно(В) :- сднф_обратно(В), скнф_обратно(В).
сднф_обратно(В) :- сднф(В, Ф), вектор2(Ф, В).
скнф_обратно(В) :- скнф(В, Ф), вектор2(Ф, В).

% === 4. Полином Жегалкина: треугольник Паскаля по модулю 2 ===

% жегалкин(В, К): коэффициенты — левая сторона треугольника
% пример: жегалкин([1, 1, 0, 1], [1, 0, 1, 1]) — это 1 ⊕ x ⊕ xy.  контрпример: жегалкин([1, 1, 0, 1], [1, 1, 0, 1]).
жегалкин([А], [А]).
жегалкин([А, Б | Ост], [А | К]) :- соседи([А, Б | Ост], С), жегалкин(С, К).

% соседи(Строка, Ниже): строка треугольника под данной — суммы соседей по модулю 2
% пример: соседи([1, 1, 0, 1], [0, 1, 1]).  контрпример: соседи([1, 1, 0, 1], [1, 0, 1]).
соседи([_], []).
соседи([А, Б | Ост], [С | Ниже]) :- С is А xor Б, соседи([Б | Ост], Ниже).

% === 5. Законы: верен ли на всех наборах ===

% набор3(Н): все наборы значений x, y, z
% пример: набор3([x-1, y-0, z-1]).  контрпример: набор3([x-2, y-0, z-0]).
набор3([x-X, y-Y, z-Z]) :- бит(X), бит(Y), бит(Z).

% значения_пары(Л, П, А, Б): значения двух формул на одном наборе
% пример: значения_пары(x, не(x), 1, 0).  контрпример: значения_пары(x, x, 1, 0).
значения_пары(Л, П, А, Б) :- набор3(Н), знач(Л, Н, А), знач(П, Н, Б).

% расходятся(Л, П): есть набор, где формулы различны
% пример: расходятся(x, y).  контрпример: расходятся(не(не(x)), x).
расходятся(Л, П) :- значения_пары(Л, П, А, Б), А =\= Б.

% закон_верен(Н): закон номер Н верен на всех наборах
% пример: закон_верен(10) — де Моргана.  контрпример: нет — все законы двоичные верны.
закон_верен(Н) :- закон(Н, _, Л, П), \+ расходятся(Л, П).
