"""trit.py — ядро троичной логики команды (Марьям, 25.11.2026).

Значения: 1 — да, 0 — не знаю, -1 — нет (решение учителя 25.11: 0 — «не знаю», как в книге).
Эталон — logika/kniga/prolog/bazis.pl: те же слова, те же имена, тот же порядок снизу вверх.
Основной базис {и, не, ворота, 0}; каждое слово выше собрано только из слов над ним.
Ядро не знает ни про навыки, ни про память: только значения, действия и вывод.
Проверка: python3 -I yadro-trit/proverka.py [путь к клону drakon-graf]
"""

# === 0. Трит ===
ДА = 1
НЕ_ЗНАЮ = 0
НЕТ = -1
ТРИТЫ = (НЕТ, НЕ_ЗНАЮ, ДА)
ИМЕНА = {ДА: 'да', НЕ_ЗНАЮ: 'не_знаю', НЕТ: 'нет'}
ОТСУТСТВУЕТ = 'отсутствует'


# трит: имя значения (как трит/2 эталона)
def трит(x):
    return ИМЕНА[x]


# это_трит: x — трит (как трит/1 эталона)
def это_трит(x):
    return x in ТРИТЫ


# === 1. Основной базис ===
# не: меняет знак
def не(x):
    return -x


# и: берёт меньшее
def и(x, y):
    return min(x, y)


# ворота: пропускают только 1
def ворота(x):
    ответ = НЕТ
    if x == ДА:
        ответ = ДА
    return ответ


# ноль: число «не знаю»
def ноль():
    return НЕ_ЗНАЮ


# === 2. Следующий уровень ===
# не_и: ¬(x ∧ y)
def не_и(x, y):
    return не(и(x, y))


# или: ¬(¬x ∧ ¬y) — берёт большее
def или(x, y):
    return не_и(не(x), не(y))


# погасло: ¬ворота(x)
def погасло(x):
    return не(ворота(x))


# погасли_оба: a ∧ ¬ворота(x)
def погасли_оба(a, x):
    return и(a, погасло(x))


# не_знаю: пропускает только 0: ¬ворота(x) ∧ ¬ворота(¬x)
def не_знаю(x):
    return погасли_оба(погасло(x), не(x))


# возможно: ¬ворота(¬x) — всё, кроме -1
def возможно(x):
    return погасло(не(x))


# с_нулём: x ∧ 0
def с_нулём(x):
    return и(x, ноль())


# подтвердить: a ∨ (y ∧ 0) — «нет» в a остаётся, только если y = -1
def подтвердить(a, y):
    return или(a, с_нулём(y))


# === 3. Действия ===
# основание: (x ∧ b) ∨ (¬b ∧ 0) — есть основание — x, нет — 0
def основание(x, б):
    return подтвердить(и(x, б), не(б))


# согласие: (x ∧ y) ∨ ((x ∨ y) ∧ 0) — одинаково — значение, разное — 0
def согласие(x, y):
    return подтвердить(и(x, y), или(x, y))


# есть_ли: нашёл ∨ (¬полный ∧ 0) — «нет» только при полном списке
def есть_ли(нашёл, полный):
    return подтвердить(нашёл, не(полный))


# срабатывает: по «отсутствует» правило не запускается
def срабатывает(x):
    ответ = ДА
    if x == ОТСУТСТВУЕТ:
        ответ = НЕТ
    return ответ


# === 4. Следование (как chast2-B.pl, Клини) ===
# сл: ¬x ∨ y
def сл(x, y):
    return или(не(x), y)


# экв: (x → y) ∧ (y → x)
def экв(x, y):
    return и(сл(x, y), сл(y, x))


# === 5. Много значений (как chast2-D.pl) ===
# согласие_всех: согласие по списку, слева направо
def согласие_всех(список):
    итог = список[0]
    for x in список[1:]:
        итог = согласие(итог, x)
    return итог


# или_всех: большее по списку; пустой — -1
def или_всех(список):
    итог = НЕТ
    for x in список:
        итог = или(итог, x)
    return итог


# и_всех: меньшее по списку; пустой — 1
def и_всех(список):
    итог = ДА
    for x in список:
        итог = и(итог, x)
    return итог


# неотвратимо: все варианты согласны, и список вариантов полный
def неотвратимо(список, полный):
    return основание(согласие_всех(список), полный)


# может_быть: хоть один вариант — да; «нет» только при полном списке
def может_быть(список, полный):
    return есть_ли(или_всех(список), полный)


# === 6. Таблицы ===
# вектор1: ответы слова с одной буквой при x = -1, 0, 1
def вектор1(слово):
    return [слово(x) for x in ТРИТЫ]


# вектор2: девять ответов слова с двумя буквами, строка за строкой
def вектор2(слово):
    return [слово(x, y) for x in ТРИТЫ for y in ТРИТЫ]
