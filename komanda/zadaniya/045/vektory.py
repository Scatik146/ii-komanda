"""vektory.py — формулы кандидатов ОЧ-34…40 и их векторы против векторов правил листка (книга, шаг Е).

Векторы — перебором трёх значений трита (одна переменная) или девяти клеток (две: a = −1, 0, 1; b = −1, 0, 1).
Совпадение вектора — дубль по формуле. Дубль ли по смыслу — решает вход (что подаётся на a и b), это пишет человек.
"""
T = (-1, 0, 1)


# vorota: пропускают только 1
def vorota(x):
    return 1 if x == 1 else -1


# osnovanie: (x ∧ b) ∨ (¬b ∧ 0) — книга, правило 1
def osnovanie(x, b):
    return max(min(x, b), min(-b, 0))


# oba: оба точно(a, b) = ворота(a) ∧ ворота(b)
def oba(a, b):
    return min(vorota(a), vorota(b))


# soglasie: согласие — 1 или −1, если оба так; иначе 0 (книга, правило 9)
def soglasie(a, b):
    return a if a == b and a != 0 else 0


# vektor: вектор слова одной или двух переменных (перебор значений)
def vektor(slovo, mest):
    vhody = [(x,) for x in T] if mest == 1 else [(a, b) for a in T for b in T]
    return tuple(slovo(*v) for v in vhody)


LISTOK = {  # вектор → строки листка (по книге: «Вектором …» у правил шага Е)
    vektor(osnovanie, 2): 'основание: Л1, Л15, Л31, Л37 (и формулой Л2, Л8)',
    vektor(vorota, 1): 'ворота: Л19, Л21, Л35',
    vektor(oba, 2): 'оба точно: Л17, Л18, Л27, Л30, Л39',
    vektor(soglasie, 2): 'согласие: Л9, Л28',
}

KANDIDATY = [
    ('ОЧ-34', 'проверено для класса(р, в среде) = основание(р, в среде)', osnovanie, 2),
    ('ОЧ-35', 'искать сестёр(о) = ворота(о), о — нашёл ли ошибку в слове', vorota, 1),
    ('ОЧ-36', 'собирать(п) = ворота(п), п — задан ли потолок', vorota, 1),
    ('ОЧ-37', 'в отчёте(сделано, ответ) = основание(сделано, ответ исполнителя)', osnovanie, 2),
    ('ОЧ-38', 'верить копии(к, сверена) = основание(к, сверена с подлинником)', osnovanie, 2),
    ('ОЧ-39', 'готово(п, пр) = оба точно(п, пр)', oba, 2),
    ('ОЧ-40', 'принять(да1, да2) = согласие(да1, да2)', soglasie, 2),
]

for nomer, formula, slovo, mest in KANDIDATY:
    v = vektor(slovo, mest)
    print(f'{nomer}: {formula}\n   вектор {v} → совпадает: {LISTOK.get(v, "ни с одним")}')
