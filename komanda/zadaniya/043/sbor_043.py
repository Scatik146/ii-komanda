# imya_fajla: короткое имя файла книги
def imya_fajla(put):
    return put.split("/")[-1]

# citata: строки в виде цитаты; пусто - пометка
def citata(stroki):
    if not stroki:
        return "> (ничего - кусок новый)"
    while stroki and not stroki[-1].strip():
        stroki = stroki[:-1]
    return "\n".join("> " + s if s.strip() else ">" for s in stroki)

# gde_gruppa: где в тексте стоит группа (без повторов)
def gde_gruppa(vse, nomera):
    mesta = []
    for n in nomera:
        put, stroka, z = vse[n - 1][0], vse[n - 1][1], vse[n - 1][2]
        m = f"{imya_fajla(put)}, {z}"
        if m not in mesta:
            mesta.append(m)
    return "; ".join(mesta)

# kusok_tekst: один кусок экспертизы
def kusok_tekst(vse, k, nomera, otvet):
    chasti = [f"### Кусок {k}", "", f"**Где:** {gde_gruppa(vse, nomera)}", "",
              f"**Отвечает на замечание сводки 041:** {otvet}", ""]
    for n in nomera:
        put, stroka, z, bylo, stalo = vse[n - 1]
        if len(nomera) > 1:
            chasti += [f"*{imya_fajla(put)}, строка {stroka}, {z}*", ""]
        chasti += ["**Было:**", "", citata(bylo), "", "**Стало:**", "", citata(stalo), ""]
    chasti += ["**Ответ:** снято ли замечание - … · новое противоречие с соседями - …", "", "---", "", ""]
    return "\n".join(chasti)

# vse_kuski: тексты всех кусков по порядку
def vse_kuski():
    vse = kuski()
    return [kusok_tekst(vse, k, g[0], g[1]) for k, g in enumerate(GRUPPY, 1)]

# razbit: куски по частям не длиннее PREDEL
def razbit(teksty):
    chasti, tek = [], []
    for t in teksty:
        if tek and sum(map(len, tek)) + len(t) > PREDEL:
            chasti.append(tek); tek = []
        tek.append(t)
    return chasti + [tek]

# shapka: начало части
def shapka(n, vsego, a, b):
    return (f"# Экспертиза 043 - часть {n} из {vsego} (куски {a}-{b})\n\n"
            "К заданию `komanda/zadaniya/043-ekspertiza-pravok-E.md`. Часть 2 книги, шаг Е, правки после сводки 041. "
            "Показаны только изменённые места: «было → стало». Номера правил сквозные, 1-46.\n\n"
            "По каждому куску два вопроса: **1) снято ли замечание** (да / частично / нет - и почему); "
            "**2) нет ли нового противоречия** с соседними правилами и кусками (цитата и номер).\n\n---\n\n")

# metka: конец части
def metka(n, vsego, a, b):
    return f"**КОНЕЦ ЧАСТИ {n} ИЗ {vsego}. Куски {a}-{b}.**\n"

# zapisat: части в файлы, отчёт о размерах
def zapisat():
    chasti = razbit(vse_kuski())
    k = 1
    for n, ch in enumerate(chasti, 1):
        a, b = k, k + len(ch) - 1
        tekst = shapka(n, len(chasti), a, b) + "".join(ch) + metka(n, len(chasti), a, b)
        open(f"{VYHOD}chast-{n}.md", "w").write(tekst)
        print(f"часть {n}: куски {a}-{b}, {len(tekst)} знаков")
        k = b + 1

if __name__ == "__main__":
    zapisat()
