% Запуск: стенд drakon-graf site/experiments/prolog/lib (swipl-wasm) в node — komanda/derevo/proverit.cjs.

:- encoding(utf8).
:- table предок/2.

% предок(X, Y): Y выше X по связям «родитель».
предок(X, Y) :- узел(X, Y, _).
предок(X, Z) :- узел(X, Y, _), предок(Y, Z).

% нет_родителя(X): родитель X — не корень и не узел.
нет_родителя(X) :- узел(X, Р, _), Р \== корень, \+ узел(Р, _, _).

% чужой_статус(X): статус X не из списка пяти.
чужой_статус(X) :- узел(X, _, С), \+ статус(С).

% в_цикле(X): X сам себе предок.
в_цикле(X) :- узел(X, _, _), предок(X, X).

% чужая_опора(X): X опирается на то, что не узел (или сам X не узел).
чужая_опора(X) :- опирается(X, Y), \+ оба_узлы(X, Y).
оба_узлы(X, Y) :- узел(X, _, _), узел(Y, _, _).

% дерево_верно: ни одной ошибки четырёх видов.
дерево_верно :- \+ нет_родителя(_), \+ чужой_статус(_), \+ в_цикле(_), \+ чужая_опора(_).

